#!/usr/bin/env python3
"""Unit test coverage summary for Roastbook.

Run after:  ./gradlew testDebugUnitTest createDebugUnitTestCoverageReport
Usage:      python3 scripts/coverage.py [--min 95] [--files N]

Reads AGP's JaCoCo XML report, drops generated code (Hilt, Dagger, Room, Compose singletons, R,
BuildConfig) and the named SDK adapters below, and prints line and branch coverage with and
without those adapters. With --min, exits 1 when line coverage (adapters excluded) is below it.
"""
import argparse
import re
import sys
import xml.etree.ElementTree as ET

REPORT = "app/build/reports/coverage/test/debug/report.xml"

# Generated by annotation processors or the Compose compiler; never written by hand.
GENERATED = re.compile(
    r"(Hilt_|_Factory|_MembersInjector|_HiltModules|_Impl\b|_Impl\$|Dagger|_GeneratedInjector|"
    r"_ComponentTreeDeps|hilt_aggregated_deps|_Provide|BuildConfig|ComposableSingletons|"
    r"_AssistedFactory|_HiltComponents|/R$|/R\$|^dagger/)"
)

# Thin adapters over runtimes that do not exist on the JVM. Each is excluded by class, so pure
# logic in the same file (cleanApiKey, the crop geometry in MlKitSubjectCropper's companion)
# still counts. Anything added here needs a reason that names the missing runtime.
EXCLUDED = {
    r"dev/roastbook/app/reader/LiteRtLocalReader($|\$)": "LiteRT-LM native runtime",
    r"dev/roastbook/app/extraction/GeminiNanoTier($|\$)": "AICore (Gemini Nano) system service",
    r"dev/roastbook/app/extraction/MlKitOcrTier($|\$)": "ML Kit text recognition native model",
    r"dev/roastbook/app/vision/MlKitSubjectCropper($|\$(?!Companion))": "ML Kit subject segmentation (Play services)",
    r"dev/roastbook/app/cloud/KeystoreSecretStore($|\$)": "AndroidKeyStore provider",
    r"dev/roastbook/app/MainActivity($|\$)": "Hilt activity entry point",
    r"dev/roastbook/app/RoastbookApp($|\$)": "Hilt application entry point",
    r"dev/roastbook/app/di/(DatabaseModule|TierModule)($|\$)": "Hilt module wiring",
}
EXCLUDED_RE = [(re.compile(p), why) for p, why in EXCLUDED.items()]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", default=REPORT)
    ap.add_argument("--min", type=float, default=None)
    ap.add_argument("--files", type=int, default=25, help="how many least-covered files to list")
    args = ap.parse_args()

    root = ET.parse(args.report).getroot()
    totals = {"kept": {}, "all": {}}
    per_file = {}
    for pkg in root.findall("package"):
        for cls in pkg.findall("class"):
            name = cls.get("name")
            if GENERATED.search(name):
                continue
            excluded = any(r.search(name) for r, _ in EXCLUDED_RE)
            counters = {c.get("type"): (int(c.get("missed")), int(c.get("covered"))) for c in cls.findall("counter")}
            for kind in ("LINE", "BRANCH"):
                missed, covered = counters.get(kind, (0, 0))
                for scope in ("all",) + (() if excluded else ("kept",)):
                    t = totals[scope].setdefault(kind, [0, 0])
                    t[0] += missed
                    t[1] += covered
            if not excluded:
                f = pkg.get("name") + "/" + (cls.get("sourcefilename") or "?")
                m, c = counters.get("LINE", (0, 0))
                acc = per_file.setdefault(f, [0, 0])
                acc[0] += m
                acc[1] += c

    def pct(scope, kind):
        m, c = totals[scope].get(kind, [0, 0])
        return 100.0 * c / max(1, m + c), c, m + c

    for scope, label in (("kept", "adapters excluded"), ("all", "everything")):
        lp, lc, lt = pct(scope, "LINE")
        bp, bc, bt = pct(scope, "BRANCH")
        print(f"{label:18} line {lp:5.1f}% ({lc}/{lt})   branch {bp:5.1f}% ({bc}/{bt})")
    print("\nExcluded adapters:")
    for _, why in EXCLUDED_RE:
        print(f"  - {why}")
    print(f"\nLeast-covered files (missed lines):")
    for f, (m, c) in sorted(per_file.items(), key=lambda kv: -kv[1][0])[: args.files]:
        if m:
            print(f"  {m:4} missed  {100.0 * c / max(1, m + c):5.1f}%  {f}")

    if args.min is not None:
        lp, _, _ = pct("kept", "LINE")
        if lp < args.min:
            print(f"\nFAIL: line coverage {lp:.1f}% is below {args.min}%")
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
